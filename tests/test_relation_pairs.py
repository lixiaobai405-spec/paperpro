"""Independent-GT work-relation candidates for an experimental CPU baseline.

All test applicants and files are synthetic. Labels are GT entry identities,
NEVER scores generated by PaperPro. The fixed 20-file holdout is excluded
from training even though it is available for final read-only evaluation.
"""
from __future__ import annotations

import pymupdf
import pytest

from app.diagnosis.annotation_alignment import align_independent_annotations
from app.diagnosis.relation_pairs import build_relation_pairs, FEATURE_NAMES
from scripts.benchmark_external_resume_corpus import IDS
from tests.test_work_relation_geometry import _pdf


def two_jobs():
    data=_pdf(extra_row=True)
    gt={"workExperience":[
        {"position":"平台运营","companyName":"虚构技术有限公司"},
        {"position":"业务分析","companyName":"合成软件有限公司"},
    ]}
    return data,gt


def test_two_independent_gt_jobs_yield_two_positive_and_two_hard_negative_pairs():
    data,gt=two_jobs()
    aligned=align_independent_annotations(data,gt)
    pairs=build_relation_pairs(aligned,gt,source_id=21,holdout_ids=IDS,training=True)
    assert len(pairs)==4
    assert sum(row["label"]==1 for row in pairs)==2
    assert sum(row["label"]==0 for row in pairs)==2
    assert all(not any(key in row for key in ("source_line","companyName","position"))
               for row in pairs)
    assert all(len(row["features"])==len(FEATURE_NAMES) for row in pairs)
    assert all(all(isinstance(x,float) and -1<=x<=1 for x in row["features"])
               for row in pairs)
    assert all(row["source_id"]==21 for row in pairs)
    assert all(row["label_source"]=="independent_gt_work_record" for row in pairs)
    assert all(row["ready_for_deployment"] is False for row in pairs)


def test_repeated_employer_location_must_not_create_false_negative_pairs():
    data=_pdf(extra_row=True)
    gt={"workExperience":[
        {"position":"平台运营","companyName":"虚构技术有限公司"},
        {"position":"业务分析","companyName":"虚构技术有限公司"},
    ]}
    pairs=build_relation_pairs(
        align_independent_annotations(data,gt),gt,
        source_id=22,holdout_ids=IDS,training=True
    )
    assert pairs==[]


def test_train_split_rejects_pinned_holdout_before_any_pair_creation():
    data,gt=two_jobs()
    aligned=align_independent_annotations(data,gt)
    with pytest.raises(ValueError,match="保留测试集"):
        build_relation_pairs(aligned,gt,source_id=IDS[0],
                             holdout_ids=IDS,training=True)
    candidate_holdout=build_relation_pairs(
        aligned,gt,source_id=IDS[0],holdout_ids=IDS,training=False
    )
    assert len(candidate_holdout)==4
    assert all(row["split"]=="holdout_evaluation" for row in candidate_holdout)


def test_absent_or_ambiguous_positions_cannot_be_imaginary_negative_labels():
    data,gt=two_jobs()
    doc=pymupdf.open(stream=data,filetype="pdf")
    page=doc[0]
    page.insert_font(fontname="SyntheticCN",fontfile="C:/Windows/Fonts/simhei.ttf")
    page.insert_text((398,440),"平台运营",fontsize=11,fontname="SyntheticCN")
    repeated=doc.tobytes()
    doc.close()
    pairs=build_relation_pairs(
        align_independent_annotations(repeated,gt),gt,
        source_id=23,holdout_ids=IDS,training=True
    )
    # Only record 1 retains a unique role anchor; uncertain record 0
    # produces neither a positive example nor cross-record negatives.
    assert len(pairs)==1
    assert pairs[0]["label"]==1
