"""Counterfactual independent synthetic acceptance gates.

Expected pairwise relations are authored as behavior constraints, not
generated by PaperPro scoring weights or hiring outcomes.
"""
from __future__ import annotations

from app.diagnosis.counterfactual_bench import build_pairs, evaluate_pairs
from app.diagnosis.scoring import score_match


def test_independent_counterfactual_relations_across_four_job_families():
    result = evaluate_pairs(per_family=20, seed=1021)
    assert result["role_families"] == 4
    assert result["synthetic_pairs"] >= 560
    assert result["criterion_validated"] is False
    assert result["failed_pairs"] == 0, result["counterexamples"]
    assert result["pairwise_pass_rate"] == 1.0
    assert all(item["passed"] == item["total"]
               for item in result["properties"].values())


def test_individual_repeated_claims_do_not_confer_extra_points():
    pairs = build_pairs(per_family=1, seed=19)
    for pair in pairs:
        if pair.property_name not in {"repeated_project_claim", "duplicate_job_period"}:
            continue
        before = score_match(pair.original, pair.target)["score"]
        after = score_match(pair.changed, pair.target)["score"]
        assert after == before, (pair.scenario_id, before, after)


def test_multiple_seeds_and_richer_jd_variants():
    from scripts.stress_test_scoring import run_suite
    result = run_suite(seeds=(1021, 2026, 99), per_family=20)
    assert result["total_pair_checks"] == 1680
    assert result["failed_checks"] == 0
    assert result["criterion_validated"] is False
    assert len(set(p.target.job_description
                   for p in build_pairs(per_family=20, seed=1021))) >= 40


def test_offline_cli_prints_only_aggregate_synthetic_metrics():
    import subprocess
    import json
    import sys
    process = subprocess.run(
        [sys.executable, "-m", "scripts.stress_test_scoring", "--per-family", "2"],
        check=False, text=True, capture_output=True, timeout=45,
    )
    assert process.returncode == 0, process.stderr
    result = json.loads(process.stdout)
    assert result["total_pair_checks"] == 4 * 2 * 7 * 3
    assert result["failed_checks"] == 0
    assert result["criterion_validated"] is False
    assert "api_key" not in process.stdout.lower()


def test_synthetic_pair_generation_is_reproducible():
    def summarize(seed):
        return [
            (pair.scenario_id, pair.property_name,
             pair.target.job_description, pair.expected)
            for pair in build_pairs(per_family=3, seed=seed)
        ]
    assert summarize(37) == summarize(37)
    assert summarize(37) != summarize(38)
